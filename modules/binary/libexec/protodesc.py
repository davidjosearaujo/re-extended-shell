#!/usr/bin/env python3
"""Recovers .proto files from the protobuf descriptors compiled into files.

Code generated by protoc for the full runtime (C++, Java, Go, Python, ...)
embeds each .proto file as a serialized FileDescriptorProto. This finds them
in raw bytes, in the string table of dex files, in Python sources, in gzip
streams (older Go code) and inside zip archives (APK, JAR, AAR, ...), decodes
them with a small decoder of the protobuf wire format (no protobuf package
needed), and writes them back as .proto source.

Usage: protodesc.py OUT_DIR ALL INPUT...
  OUT_DIR  where the .proto files go, by their own path (a/b.proto)
  ALL      "1" to keep google/protobuf/*.proto too
Prints one tab-separated line per file found:
  written|skipped|duplicate  NAME  SOURCE  MESSAGES  ENUMS  SERVICES  NOTE
Part of RE Extended Shell (bin/proto-extract). Standard library only.
"""
import ast
import os
import re
import sys
import zipfile
import zlib

MAX_MEMBER = 512 << 20          # skip archive members bigger than this


# --- Wire format ---------------------------------------------------------------

class Malformed(Exception):
    pass


def varint(buf, pos):
    result = shift = 0
    while True:
        if pos >= len(buf):
            raise Malformed("truncated varint")
        b = buf[pos]
        pos += 1
        result |= (b & 0x7F) << shift
        if not b & 0x80:
            return result, pos
        shift += 7
        if shift > 63:
            raise Malformed("varint too long")


def fields(buf):
    """Yields (number, wire_type, value) for each field of a message."""
    pos = 0
    while pos < len(buf):
        key, pos = varint(buf, pos)
        num, wt = key >> 3, key & 7
        if num == 0:
            raise Malformed("field 0")
        if wt == 0:
            val, pos = varint(buf, pos)
        elif wt == 1:
            if pos + 8 > len(buf):
                raise Malformed("truncated fixed64")
            val, pos = buf[pos:pos + 8], pos + 8
        elif wt == 2:
            n, pos = varint(buf, pos)
            if pos + n > len(buf):
                raise Malformed("truncated bytes")
            val, pos = buf[pos:pos + n], pos + n
        elif wt == 5:
            if pos + 4 > len(buf):
                raise Malformed("truncated fixed32")
            val, pos = buf[pos:pos + 4], pos + 4
        else:
            raise Malformed("wire type %d" % wt)
        yield num, wt, val


def text(v):
    try:
        return v.decode("utf-8")
    except (AttributeError, UnicodeDecodeError):
        raise Malformed("not text")


def message(buf, schema):
    """Decodes buf with schema {number: (name, kind, repeated)}; kind is
    "str", "int", "bool" or a nested schema. Unknown fields are ignored."""
    out = {}
    for num, wt, val in fields(buf):
        if num not in schema:
            continue
        name, kind, rep = schema[num]
        if kind == "str":
            if wt != 2:
                raise Malformed("%s: wire type" % name)
            v = text(val)
        elif kind in ("int", "bool"):
            if wt == 2:          # packed
                vals, p = [], 0
                while p < len(val):
                    x, p = varint(val, p)
                    vals.append(x)
                out.setdefault(name, []).extend(vals)
                continue
            if wt != 0:
                raise Malformed("%s: wire type" % name)
            v = bool(val) if kind == "bool" else val
        else:
            if wt != 2:
                raise Malformed("%s: wire type" % name)
            v = message(val, kind)
        if rep:
            out.setdefault(name, []).append(v)
        else:
            out[name] = v
    return out


# The parts of descriptor.proto that a .proto file shows
RANGE = {1: ("start", "int", False), 2: ("end", "int", False)}
FIELD_OPTIONS = {2: ("packed", "bool", False), 3: ("deprecated", "bool", False), 5: ("lazy", "bool", False)}
FIELD = {1: ("name", "str", False), 2: ("extendee", "str", False), 3: ("number", "int", False),
         4: ("label", "int", False), 5: ("type", "int", False), 6: ("type_name", "str", False),
         7: ("default_value", "str", False), 8: ("options", FIELD_OPTIONS, False),
         9: ("oneof_index", "int", False), 10: ("json_name", "str", False),
         17: ("proto3_optional", "bool", False)}
ENUM_VALUE = {1: ("name", "str", False), 2: ("number", "int", False)}
ENUM = {1: ("name", "str", False), 2: ("value", ENUM_VALUE, True), 3: ("options", {2: ("allow_alias", "bool", False)}, False),
        4: ("reserved_range", RANGE, True), 5: ("reserved_name", "str", True)}
MESSAGE = {1: ("name", "str", False), 2: ("field", FIELD, True), 4: ("enum_type", ENUM, True),
           5: ("extension_range", RANGE, True), 6: ("extension", FIELD, True),
           7: ("options", {7: ("map_entry", "bool", False)}, False),
           8: ("oneof_decl", {1: ("name", "str", False)}, True),
           9: ("reserved_range", RANGE, True), 10: ("reserved_name", "str", True)}
MESSAGE[3] = ("nested_type", MESSAGE, True)
METHOD = {1: ("name", "str", False), 2: ("input_type", "str", False), 3: ("output_type", "str", False),
          5: ("client_streaming", "bool", False), 6: ("server_streaming", "bool", False)}
SERVICE = {1: ("name", "str", False), 2: ("method", METHOD, True)}
FILE_OPTIONS = {1: ("java_package", "str", False), 8: ("java_outer_classname", "str", False),
                10: ("java_multiple_files", "bool", False), 11: ("go_package", "str", False),
                36: ("objc_class_prefix", "str", False), 37: ("csharp_namespace", "str", False),
                9: ("optimize_for", "int", False)}
FILE = {1: ("name", "str", False), 2: ("package", "str", False), 3: ("dependency", "str", True),
        4: ("message_type", MESSAGE, True), 5: ("enum_type", ENUM, True), 6: ("service", SERVICE, True),
        7: ("extension", FIELD, True), 8: ("options", FILE_OPTIONS, False),
        10: ("public_dependency", "int", True), 12: ("syntax", "str", False), 14: ("edition", "int", False)}
# FileDescriptorProto's fields and their wire types, to find where one ends
FILE_WIRE = {1: (2,), 2: (2,), 3: (2,), 4: (2,), 5: (2,), 6: (2,), 7: (2,), 8: (2,), 9: (2,),
             10: (0, 2), 11: (0, 2), 12: (2,), 14: (0,)}
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


# --- Finding descriptors ---------------------------------------------------------

NAME_CHARS = frozenset(b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789_./-")


def descriptor_end(buf, pos):
    """Walks FileDescriptorProto fields from pos, which protoc writes in field
    order: stops at a lower field number, an unknown field or a wrong wire
    type. Returns (end, truncated): truncated if the buffer ends mid-field."""
    last = 0
    while pos < len(buf):
        start = pos
        try:
            key, pos = varint(buf, pos)
        except Malformed:
            return start, True
        num, wt = key >> 3, key & 7
        if num < last or num not in FILE_WIRE or wt not in FILE_WIRE[num] \
                or (num == last and num in (1, 2, 12, 14)):
            return start, False
        try:
            if wt == 0:
                _, pos = varint(buf, pos)
            else:
                n, pos = varint(buf, pos)
                if pos + n > len(buf):
                    return start, True
                pos += n
        except Malformed:
            return start, True
        last = num
    return pos, False


def plausible(fd):
    def names(msgs):
        for m in msgs:
            yield m.get("name", "")
            for f in m.get("field", []):
                yield f.get("name", "")
            yield from names(m.get("nested_type", []))
    return all(IDENT.match(n) for n in names(fd.get("message_type", []))) \
        and all(IDENT.match(e.get("name", "")) for e in fd.get("enum_type", []))


def scan(buf, source, found):
    """Finds the descriptors in buf: a field 1 tag (0x0a), a length, then a
    name ending in .proto."""
    # Each ".proto", then back over the characters a name is made of (faster
    # than a regex over every run of text in a big binary)
    i = buf.find(b".proto")
    while i != -1:
        end = i + 6
        name_start = i
        while name_start > 0 and buf[name_start - 1] in NAME_CHARS and i - name_start < 1024:
            name_start -= 1
        candidates(buf, name_start, end, source, found)
        i = buf.find(b".proto", end)


def candidates(buf, name_start, end, source, found):
    """Tries the starts of the name that ends at end. The name's own length
    check rejects what isn't one (.protobuf, a ".proto" inside text, ...)."""
    # The walk back may have swallowed the length byte (it can be a letter or
    # a digit): try each start where a tag and a matching length precede
    for k in range(name_start, min(name_start + 4, end - 6)):
        name = buf[k:end]
        n = len(name)
        if n < 128:
            ok = k >= 2 and buf[k - 1] == n and buf[k - 2] == 0x0A
            start = k - 2
        else:
            ok = k >= 3 and buf[k - 3] == 0x0A and buf[k - 2] == (n & 0x7F) | 0x80 and buf[k - 1] == n >> 7
            start = k - 3
        if not ok:
            continue
        stop, truncated = descriptor_end(buf, start)
        try:
            fd = message(buf[start:stop], FILE)
        except Malformed:
            continue
        if fd.get("name") != name.decode("latin-1") or not plausible(fd):
            continue
        found.append((fd, buf[start:stop], source, truncated))
        return


def dex_strings(buf):
    """The strings of a dex file that mention .proto, as Latin-1 bytes (how
    protoc's Java code stores a descriptor: one char per byte)."""
    if len(buf) < 0x70:
        return
    size = int.from_bytes(buf[0x38:0x3C], "little")
    off = int.from_bytes(buf[0x3C:0x40], "little")
    for i in range(size):
        p = int.from_bytes(buf[off + 4 * i:off + 4 * i + 4], "little")
        try:
            _, p = varint(buf, p)          # length in UTF-16 units
            end = buf.index(b"\0", p)
        except (Malformed, ValueError):
            continue
        raw = buf[p:end]
        if b"proto" not in raw:
            continue
        out, j, ok = bytearray(), 0, True
        while j < len(raw):        # Modified UTF-8
            b = raw[j]
            if b < 0x80:
                c, j = b, j + 1
            elif b & 0xE0 == 0xC0 and j + 1 < len(raw):
                c, j = (b & 0x1F) << 6 | raw[j + 1] & 0x3F, j + 2
            elif b & 0xF0 == 0xE0 and j + 2 < len(raw):
                c, j = (b & 0x0F) << 12 | (raw[j + 1] & 0x3F) << 6 | raw[j + 2] & 0x3F, j + 3
            else:
                ok = False
                break
            if c > 0xFF:
                ok = False
                break
            out.append(c)
        if ok:
            yield bytes(out)


PY_LITERAL = re.compile(rb"""(?:serialized_pb\s*=|AddSerializedFile\()\s*(b'(?:[^'\\]|\\.)*'|b"(?:[^"\\]|\\.)*")""", re.S)
# The header Go's compress/gzip writes at best compression, as protoc-gen-go did
GZIP = re.compile(rb"\x1f\x8b\x08\x00\x00\x00\x00\x00\x02\xff")


def search(buf, source, found, depth=0):
    """Everything in buf: raw, then by the kind of file it is."""
    if depth > 3:
        return
    if buf[:4] == b"PK\x03\x04":
        try:
            import io
            with zipfile.ZipFile(io.BytesIO(buf)) as z:
                for info in z.infolist():
                    if info.is_dir() or info.file_size > MAX_MEMBER:
                        continue
                    search(z.read(info), source + "!" + info.filename, found, depth + 1)
        except (zipfile.BadZipFile, OSError, RuntimeError, NotImplementedError, zlib.error):
            scan(buf, source, found)
        return
    if buf[:4] == b"dex\n":
        # Only through the string table: in the raw bytes a descriptor is
        # Modified UTF-8, which mangles every byte over 0x7f and every NUL
        for s in dex_strings(buf):
            scan(s, source, found)
        return
    scan(buf, source, found)
    if b".proto" in buf and (b"serialized_pb" in buf or b"AddSerializedFile" in buf):
        for m in PY_LITERAL.finditer(buf):
            try:
                scan(ast.literal_eval(m.group(1).decode("latin-1")), source, found)
            except (ValueError, SyntaxError):
                pass
    # gzipped descriptors (Go code generated before protobuf-go v2); sliced
    # through a memoryview, which doesn't copy
    view = memoryview(buf)
    for m in GZIP.finditer(buf):
        try:
            d = zlib.decompressobj(31)
            data = d.decompress(view[m.start():m.start() + (4 << 20)], 16 << 20)
        except zlib.error:
            continue
        if b".proto" in data:
            scan(data, source + "!gzip@0x%x" % m.start(), found)


# --- Writing .proto source -----------------------------------------------------------

TYPES = {1: "double", 2: "float", 3: "int64", 4: "uint64", 5: "int32", 6: "fixed64", 7: "fixed32",
         8: "bool", 9: "string", 10: "group", 11: "message", 12: "bytes", 13: "uint32", 14: "enum",
         15: "sfixed32", 16: "sfixed64", 17: "sint32", 18: "sint64"}


def quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


class Printer:
    def __init__(self, fd):
        self.fd = fd
        self.pkg = fd.get("package", "")
        self.proto3 = fd.get("syntax") == "proto3"
        # proto3 and editions write no label but repeated (and proto3's optional)
        self.implicit = self.proto3 or "edition" in fd
        self.lines = []

    def out(self, depth, s=""):
        self.lines.append(("  " * depth + s) if s else "")

    def tname(self, t, scope):
        """A type name, relative to the package when it's in it."""
        t = t.lstrip(".")
        if self.pkg and t.startswith(self.pkg + "."):
            return t[len(self.pkg) + 1:]
        return t if not self.pkg else "." + t

    def ftype(self, f, scope):
        if f.get("type_name"):
            return self.tname(f["type_name"], scope)
        return TYPES.get(f.get("type"), "bytes")

    def field_line(self, f, scope, maps, in_oneof=False):
        label = ""
        if not in_oneof:
            if f.get("label") == 3:
                label = "repeated "
            elif f.get("label") == 2:
                label = "required "
            elif not self.implicit or f.get("proto3_optional"):
                label = "optional "
        typ = self.ftype(f, scope)
        entry = maps.get(f.get("type_name", "").lstrip("."))
        if entry and f.get("label") == 3:
            key = TYPES.get(entry[0].get("type"), "string")
            typ, label = "map<%s, %s>" % (key, self.ftype(entry[1], scope)), ""
        opts = []
        if "default_value" in f:
            d = f["default_value"]
            # A string default is stored as is, a bytes one already C-escaped
            opts.append("default = " + (quote(d) if f.get("type") == 9 else '"%s"' % d if f.get("type") == 12 else d))
        o = f.get("options", {})
        if "packed" in o:
            opts.append("packed = " + ("true" if o["packed"] else "false"))
        if o.get("deprecated"):
            opts.append("deprecated = true")
        return "%s%s %s = %d%s;" % (label, typ, f.get("name", "?"), f.get("number", 0),
                                    " [" + ", ".join(opts) + "]" if opts else "")

    def ranges(self, depth, rs, names, keyword, exclusive_end):
        if rs:
            parts = []
            for r in rs:
                s, e = r.get("start", 0), r.get("end", 0) - (1 if exclusive_end else 0)
                parts.append(str(s) if s == e else "%d to %s" % (s, "max" if e >= 536870911 else e))
            self.out(depth, "%s %s;" % (keyword, ", ".join(parts)))
        if names:
            self.out(depth, "%s %s;" % (keyword, ", ".join(quote(n) for n in names)))

    def enum(self, depth, e):
        self.out(depth, "enum %s {" % e.get("name"))
        if e.get("options", {}).get("allow_alias"):
            self.out(depth + 1, "option allow_alias = true;")
        for v in e.get("value", []):
            self.out(depth + 1, "%s = %d;" % (v.get("name"), signed32(v.get("number", 0))))
        self.ranges(depth + 1, e.get("reserved_range"), e.get("reserved_name"), "reserved", False)
        self.out(depth, "}")

    def message(self, depth, m, scope):
        name = m.get("name")
        full = scope + "." + name if scope else name
        nested = m.get("nested_type", [])
        maps = {}
        for n in nested:
            if n.get("options", {}).get("map_entry"):
                kv = {f.get("number"): f for f in n.get("field", [])}
                maps[(self.pkg + "." if self.pkg else "") + full + "." + n.get("name")] = (kv.get(1, {}), kv.get(2, {}))
        self.out(depth, "message %s {" % name)
        oneofs = m.get("oneof_decl", [])
        printed = set()
        for f in m.get("field", []):
            i = f.get("oneof_index")
            if i is None or f.get("proto3_optional") or i >= len(oneofs):
                self.out(depth + 1, self.field_line(f, full, maps))
            elif i not in printed:
                printed.add(i)
                self.out(depth + 1, "oneof %s {" % oneofs[i].get("name"))
                for g in m.get("field", []):
                    if g.get("oneof_index") == i and not g.get("proto3_optional"):
                        self.out(depth + 2, self.field_line(g, full, maps, in_oneof=True))
                self.out(depth + 1, "}")
        self.ranges(depth + 1, m.get("reserved_range"), m.get("reserved_name"), "reserved", True)
        self.ranges(depth + 1, m.get("extension_range"), None, "extensions", True)
        for e in m.get("enum_type", []):
            self.enum(depth + 1, e)
        for n in nested:
            if not n.get("options", {}).get("map_entry"):
                self.message(depth + 1, n, full)
        self.extensions(depth + 1, m.get("extension", []), full)
        self.out(depth, "}")

    def extensions(self, depth, exts, scope):
        by = {}
        for f in exts:
            by.setdefault(f.get("extendee", ""), []).append(f)
        for extendee, fs in by.items():
            self.out(depth, "extend %s {" % self.tname(extendee, scope))
            for f in fs:
                self.out(depth + 1, self.field_line(f, scope, {}))
            self.out(depth, "}")

    def render(self, source, partial):
        fd = self.fd
        self.out(0, "// %s, recovered by proto-extract (RE Extended Shell) from" % fd.get("name"))
        self.out(0, "// %s" % source)
        if partial:
            self.out(0, "// INCOMPLETE: the descriptor was cut off, later definitions are missing.")
        self.out(0)
        if "edition" in fd:
            self.out(0, 'edition = "%s";' % {1000: "2023", 1001: "2024"}.get(fd["edition"], fd["edition"]))
        else:
            self.out(0, 'syntax = "%s";' % ("proto3" if self.proto3 else "proto2"))
        self.out(0)
        if self.pkg:
            self.out(0, "package %s;" % self.pkg)
            self.out(0)
        public = set(fd.get("public_dependency", []))
        for i, dep in enumerate(fd.get("dependency", [])):
            self.out(0, 'import %s%s;' % ("public " if i in public else "", quote(dep)))
        if fd.get("dependency"):
            self.out(0)
        opts = fd.get("options", {})
        for k in ("java_package", "java_outer_classname", "go_package", "objc_class_prefix", "csharp_namespace"):
            if k in opts:
                self.out(0, "option %s = %s;" % (k, quote(opts[k])))
        if opts.get("java_multiple_files"):
            self.out(0, "option java_multiple_files = true;")
        if opts.get("optimize_for") in (2, 3):
            self.out(0, "option optimize_for = %s;" % {2: "CODE_SIZE", 3: "LITE_RUNTIME"}[opts["optimize_for"]])
        if opts:
            self.out(0)
        for m in fd.get("message_type", []):
            self.message(0, m, "")
            self.out(0)
        for e in fd.get("enum_type", []):
            self.enum(0, e)
            self.out(0)
        for s in fd.get("service", []):
            self.out(0, "service %s {" % s.get("name"))
            for r in s.get("method", []):
                self.out(1, "rpc %s(%s%s) returns (%s%s);" % (
                    r.get("name"), "stream " if r.get("client_streaming") else "", self.tname(r.get("input_type", ""), ""),
                    "stream " if r.get("server_streaming") else "", self.tname(r.get("output_type", ""), "")))
            self.out(0, "}")
            self.out(0)
        self.extensions(0, fd.get("extension", []), "")
        while self.lines and not self.lines[-1]:
            self.lines.pop()
        return "\n".join(self.lines) + "\n"


def signed32(n):
    return n - (1 << 64) if n >= 1 << 63 else n


def count(msgs):
    return sum(1 + count(m.get("nested_type", [])) for m in msgs if not m.get("options", {}).get("map_entry"))


# --- Main ------------------------------------------------------------------------------

def main():
    out_dir, keep_all, inputs = sys.argv[1], sys.argv[2] == "1", sys.argv[3:]
    found = []
    for path in inputs:
        if os.path.isdir(path):
            for root, _, files in os.walk(path):
                for f in sorted(files):
                    p = os.path.join(root, f)
                    try:
                        with open(p, "rb") as fh:
                            search(fh.read(), p, found)
                    except OSError:
                        pass
        else:
            with open(path, "rb") as fh:
                search(fh.read(), path, found)

    best = {}       # name -> (fd, raw, source, truncated); the longest complete one wins
    dupes = {}
    for fd, raw, source, truncated in found:
        name = fd["name"]
        if name in best:
            dupes.setdefault(name, []).append(source)
            old = best[name]
            if (old[3] and not truncated) or (old[3] == truncated and len(raw) > len(old[1])):
                best[name] = (fd, raw, source, truncated)
        else:
            best[name] = (fd, raw, source, truncated)

    for name in sorted(best):
        fd, raw, source, truncated = best[name]
        counts = "%d\t%d\t%d" % (count(fd.get("message_type", [])), len(fd.get("enum_type", [])), len(fd.get("service", [])))
        note = "also in %d more place(s)" % len(dupes[name]) if name in dupes else ""
        if truncated:
            note = "incomplete" + (", " + note if note else "")
        if not keep_all and name.startswith("google/protobuf/"):
            print("skipped\t%s\t%s\t%s\t%s" % (name, source, counts, note))
            continue
        rel = os.path.normpath(name).lstrip("/")
        if rel.startswith(".."):
            rel = rel.replace("..", "_")
        target = os.path.join(out_dir, rel)
        os.makedirs(os.path.dirname(target) or out_dir, exist_ok=True)
        with open(target, "w") as fh:
            fh.write(Printer(fd).render(source, truncated))
        print("written\t%s\t%s\t%s\t%s" % (name, source, counts, note))


if __name__ == "__main__":
    main()
